"""`tools/kb_network.py` queries the three knowledge-base tiers and writes a stamped artifact.

visibility: public

Run against the REAL registered EcoSIM profile, with vector search off (`--rag-k 0`) so no embedding
model loads. What each test would catch is named in its docstring. The stamp the phase-log checker
reads (`kb_network`, `profile`, `kb_commit`) is asserted here, so the two cannot disagree silently.
Account: `memory/dev_logs_adapterkit/20261015h_Phase_3_And_4_Query_The_Knowledge_Base_Before_The_Source.md`.

Author: Jing Tao with Claude on Perlmutter.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
TOOL = REPO / "tools" / "kb_network.py"
PROFILE = "ecosim-cb243228"

pytestmark = pytest.mark.skipif(not (REPO / "rag" / "graphs" / f"{PROFILE}.json").is_file(),
                                reason="the EcoSIM graph is not in this tree")


def _run(tmp_path, *args):
    out = tmp_path / "kbn"
    r = subprocess.run([sys.executable, str(TOOL), "--model", "ecosim", "--profile", PROFILE, "--rag-k", "0",
                        "--out-dir", str(out), *args], capture_output=True, text=True, timeout=120)
    js = json.loads((out / "kb_network.json").read_text()) if (out / "kb_network.json").is_file() else None
    md = (out / "kb_network.md").read_text() if (out / "kb_network.md").is_file() else ""
    return r.returncode, js, md, r.stdout + r.stderr


def test_the_artifact_carries_the_stamp_the_checker_reads(tmp_path):
    rc, js, md, out = _run(tmp_path, "--params", "RMOM")
    assert rc == 0, out
    assert js["kb_network"] == 1 and js["profile"] == PROFILE and js["kb_commit"], js
    assert md.startswith("# Knowledge-base network") and "**Generated by:**" in md and f"**Profile:** {PROFILE}" in md


def test_tier2_the_graph_network_and_reachability(tmp_path):
    """A parameter's controls edge and a direct path must appear; a path the graph lacks must say so."""
    rc, js, md, out = _run(tmp_path, "--params", "RMOM", "--outputs", "tMICROB_C_col", "ECO_GPP_col")
    edges = {(e["src"], e["rel"], e["dst"]) for e in js["tier2"]["entities"]["RMOM"]["edges"]}
    assert ("parameter:RMOM", "controls", "mechanism:Microbial_Maintenance_Respiration") in edges, edges
    reach = {(x["param"], x["output"]): x["paths"] for x in js["tier2"]["reach"]}
    assert reach[("RMOM", "tMICROB_C_col")], "a direct affects edge must be a path"
    assert reach[("RMOM", "ECO_GPP_col")] == [] and "**NOT REACHABLE**" in md
    assert any("does not reach `ECO_GPP_col`" in g for g in js["gaps"]), js["gaps"]


def test_tier1_reads_only_the_profiles_own_pinned_wiki(tmp_path):
    """Another profile's pinned wiki must never answer for this one: the legacy wiki sits in the
    same knowledge-base directory and names the same parameters."""
    rc, js, md, out = _run(tmp_path, "--params", "RMOM", "--per-name", "50")
    files = [x["file"] for x in js["tier1"]["RMOM"]["lines"]]
    assert files and all("ecosim-codebase-wiki-2dea74d9" not in f for f in files), files
    assert any("ecosim-codebase-wiki-cb243228" in f for f in files), files


def test_tier3_reads_both_memory_layers(tmp_path):
    """The model layer and, with --case, the case layer; a case keeps some entries as top-level keys."""
    rc, js, md, out = _run(tmp_path, "--params", "FCO2", "--case", "EcoSIM_Lusignan")
    assert set(js["tier3"]) == {"model", "case"}, js["tier3"].keys()
    case = js["tier3"]["case"]["files"]
    labels = [e["label"] for d in case.values() for e in d["entries"]]
    assert "fco2_is_the_rank_one_water_lever" in labels, labels


def test_case_accepts_the_path_form_and_reads_the_same_layer(tmp_path):
    """`--case use_cases/EcoSIM_Lusignan` once resolved to use_cases/use_cases/... and reported "store absent"."""
    rc, js, md, out = _run(tmp_path, "--params", "FCO2", "--case", "use_cases/EcoSIM_Lusignan/")
    case = js["tier3"]["case"]
    assert "use_cases/use_cases" not in case["store"], case["store"]
    labels = [e["label"] for d in case["files"].values() for e in d["entries"]]
    assert "fco2_is_the_rank_one_water_lever" in labels, labels
    assert "store absent" not in md


def test_an_unknown_case_is_bad_usage(tmp_path):
    rc, js, md, out = _run(tmp_path, "--params", "FCO2", "--case", "No_Such_Case")
    assert rc == 2 and js is None, out


def test_the_source_pointers_come_from_the_kb(tmp_path):
    rc, js, md, out = _run(tmp_path, "--params", "RMOM")
    assert js["source_pointers"] and all(":" in p for p in js["source_pointers"]), js["source_pointers"]
    assert "## Then the source" in md


def test_a_name_the_graph_lacks_exits_1_and_is_a_gap(tmp_path):
    rc, js, md, out = _run(tmp_path, "--params", "NOT_A_PARAMETER")
    assert rc == 1, out
    assert any("NOT_A_PARAMETER" in g for g in js["gaps"]), js["gaps"]


def test_no_names_is_bad_usage(tmp_path):
    rc, js, md, out = _run(tmp_path)
    assert rc == 2 and js is None, out
