"""Patching a knowledge base in place, and resolving which profile covers the commit in use.

visibility: public
Author: Jing Tao with Claude on Perlmutter

`tools/kb_profile.py` matches the commit a user runs against `rag/milestones.json` (a milestone's base
commit and its in-place patches); `tools/kb_patch.py` re-anchors a profile's citations to a fix
committed on top of that base and registers the fix as a patch. Both are exercised here on a
synthetic two-commit model repository and a synthetic registry, so the tests need no model checkout.

The fix inserts two lines inside routine `Alpha` (after old line 5) and modifies old line 9:

    old line   4 `Alpha`  untouched (before the insertion)
    old lines  5-8        an insertion inside the range -> content
    old line   8 `Beta`   shifted to 10
    old line   9 `Beta`   modified -> content
    old line  13 `Gamma`  shifted to 15

Each assertion names a way a tool must behave on that diff, so each is a negative control for the
rule it pins. Remove the table-row rule and the bare `:13` on the row that names nothing is read as a
line of `src/Other.F90` (named in the previous row), which did not change, so it is not re-anchored;
remove the content check and `:13` beside `zeta`, which fits both files with different outcomes, is
moved instead of left for review. Both were run and both fail.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from tools import kb_patch, kb_profile  # noqa: E402

MOD_BASE = """module Mod
contains
  subroutine Alpha(x)
    x = 1
    x = x + 1
  end subroutine Alpha
  subroutine Beta(y)
    y = 2
    y = y * 3
    y = y - 1
  end subroutine Beta
  subroutine Gamma(z)
    z = zeta
  end subroutine Gamma
end module Mod
"""
OTHER = "".join(f"  ! filler {i}\n" for i in range(1, 13)) + "  w = zeta\n"


def _git(path, *args):
    subprocess.run(["git", "-C", str(path), *args], check=True, capture_output=True, text=True)
    return subprocess.run(["git", "-C", str(path), "rev-parse", "HEAD"], capture_output=True,
                          text=True).stdout.strip()


@pytest.fixture()
def model(tmp_path):
    m = tmp_path / "model"
    (m / "src").mkdir(parents=True)
    _git(m, "init", "-q")
    _git(m, "config", "user.email", "t@t")
    _git(m, "config", "user.name", "t")
    (m / "src/Mod.F90").write_text(MOD_BASE)
    (m / "src/Other.F90").write_text(OTHER)
    _git(m, "add", ".")
    base = _git(m, "commit", "-q", "-m", "base")
    lines = MOD_BASE.splitlines(keepends=True)
    lines[8] = "    y = y * 4\n"                                    # modify old line 9
    lines[5:5] = ["    x = x * 2\n", "    x = x - 3\n"]             # insert after old line 5
    (m / "src/Mod.F90").write_text("".join(lines))
    (m / "src/New.F90").write_text("subroutine Delta(q)\n  q = 0\nend subroutine Delta\n")
    _git(m, "add", ".")
    fix = _git(m, "commit", "-q", "-m", "fix")
    return m, base, fix


WIKI_PAGE = """**Source pin:** toy commit `BASE8`

# Toy

## 1. The module

- The other file: src/Other.F90:3.
- `Alpha` sets x at src/Mod.F90:4 (Alpha); the block src/Mod.F90:5-8 is the body.
- `Beta` starts at src/Mod.F90:8 (Beta) and multiplies at src/Mod.F90:9 (Beta).

Everything below is in `src/Mod.F90`.

### 1.1 Gamma

`Gamma` sets z (`:13`).

| routine | where | note |
|---|---|---|
| filler | `:2` | see src/Other.F90:3 |
| `Gamma` | `:13` | sets z |
| plain | `:13` | no names on this row |

Both files touch `zeta` near the same line (`:13`).
"""
GENERATED = "**Generated by:** a tool\n\nsrc/Mod.F90:13 (Gamma)\n"
SEED = "parameters:\n  X:\n    code_location: src/Mod.F90:8 (Beta); src/Mod.F90:13 (Gamma)\n"


@pytest.fixture()
def kbrepo(tmp_path, model):
    m, base, fix = model
    r = tmp_path / "a2mc"
    wiki = r / "docs/kb/wiki-base"
    (wiki / "ref").mkdir(parents=True)
    (wiki / ".ipynb_checkpoints").mkdir()
    (r / "rag").mkdir()
    (wiki / "index.md").write_text("**Source pin:** toy commit `BASE8`\n\n# Index\n")
    (wiki / "page.md").write_text(WIKI_PAGE.replace("BASE8", base[:8]))
    (wiki / "ref/generated.md").write_text(GENERATED)
    (wiki / ".ipynb_checkpoints/page-checkpoint.md").write_text(WIKI_PAGE)
    (r / "seed.yaml").write_text(SEED)
    (r / "rag/milestones.json").write_text(json.dumps({"milestones": {
        "toy-old": {"adapter": "ecosim", "model_commit_built": base, "legacy": True,
                    "knowledge_base_dir": "docs/kb", "model_wiki_subdir": "wiki-base"},
        "toy-base": {"adapter": "ecosim", "model_commit_built": base, "knowledge_base_dir": "docs/kb",
                     "model_wiki_subdir": "wiki-base", "curated_yaml_path": "seed.yaml"},
        "toy-fates": {"fates_commit_built": base, "fates_api_epoch": "43.1"},
    }}, indent=2))
    return r, m, base, fix


# ---- the line map ------------------------------------------------------------------------------

def test_map_range_classifies_the_four_cases(model):
    m, base, fix = model
    ent = kb_patch.line_maps(m, base, fix)["src/Mod.F90"]
    assert kb_patch.map_range(ent, 4, 4) == ("untouched", 4, 4)
    assert kb_patch.map_range(ent, 4, 5) == ("untouched", 4, 5)
    assert kb_patch.map_range(ent, 5, 8)[0] == "content"        # insertion INSIDE the range
    assert kb_patch.map_range(ent, 8, 8) == ("shift", 10, 10)
    assert kb_patch.map_range(ent, 9, 9)[0] == "content"        # the modified line
    assert kb_patch.map_range(ent, 13, 13) == ("shift", 15, 15)


# ---- the resolver ------------------------------------------------------------------------------

def test_resolve_matches_the_base_and_prefers_the_live_profile(kbrepo):
    r, m, base, fix = kbrepo
    res = kb_profile.resolve("ecosim", commit=base, model_path=m, repo=r)
    assert (res.profile, res.via) == ("toy-base", "base")


def test_resolve_refuses_an_unregistered_fix_and_says_how_far_it_is(kbrepo):
    r, m, base, fix = kbrepo
    with pytest.raises(kb_profile.NoMatch, match=r"1 commit\(s\) AHEAD"):
        kb_profile.resolve("ecosim", commit=fix, model_path=m, repo=r)


def test_resolve_or_default_without_a_checkout(kbrepo, monkeypatch):
    r, m, base, fix = kbrepo
    monkeypatch.delenv("A2MC_MODEL_PATH", raising=False)
    res = kb_profile.resolve_or_default("ecosim", repo=r)
    assert (res.profile, res.via) == ("toy-base", "default")
    mj = json.loads((r / "rag/milestones.json").read_text())
    mj["milestones"]["toy-old"]["legacy"] = False                  # two live profiles: no guessing
    (r / "rag/milestones.json").write_text(json.dumps(mj))
    with pytest.raises(kb_profile.NoMatch):
        kb_profile.resolve_or_default("ecosim", repo=r)


# ---- the patch ---------------------------------------------------------------------------------

def test_plan_changes_nothing(kbrepo):
    r, m, base, fix = kbrepo
    before = {p: p.read_text() for p in r.rglob("*") if p.is_file()}
    assert kb_patch.run("toy-base", fix, m, apply=False, summary=None, report=None, repo=r) == 0
    assert {p: p.read_text() for p in r.rglob("*") if p.is_file()} == before


def test_apply_reanchors_flags_and_registers(kbrepo):
    r, m, base, fix = kbrepo
    wiki = r / "docs/kb/wiki-base"
    assert kb_patch.run("toy-base", fix, m, apply=True, summary="toy fix", report=None, repo=r) == 0
    page = (wiki / "page.md").read_text()
    assert "src/Mod.F90:4 (Alpha)" in page                  # untouched
    assert "src/Mod.F90:10 (Beta)" in page                  # shifted
    assert "src/Mod.F90:9 (Beta)" in page                   # content: left as written for review
    assert "src/Mod.F90:5-8" in page                        # content (insertion inside the range)
    assert "sets z (`:15`)" in page                         # bare, attributed by position + routine
    assert "| `Gamma` | `:15` | sets z |" in page          # table row, settled by content (`Gamma`)
    assert "| plain | `:15` | no names on this row |" in page   # table row, position alone: the file
    # named above the table, not the src/Other.F90 of the previous row's last column
    assert "| filler | `:2` |" in page                      # untouched whichever file it means
    assert "same line (`:13`)" in page                      # two files fit and disagree: left as is
    assert "patched to `" + fix[:8] + "`" in page           # the pin states the patch level
    assert (wiki / "ref/generated.md").read_text() == GENERATED            # regenerated, not edited
    assert (wiki / ".ipynb_checkpoints/page-checkpoint.md").read_text() == WIKI_PAGE  # never read
    seed = (r / "seed.yaml").read_text()
    assert "src/Mod.F90:10 (Beta); src/Mod.F90:15 (Gamma)" in seed
    index = (wiki / "index.md").read_text()
    assert "## Patches applied" in index and fix[:8] in index and "toy fix" in index
    ms = json.loads((r / "rag/milestones.json").read_text())["milestones"]["toy-base"]
    assert ms["patches"][-1]["commit"] == fix and ms["patches"][-1]["parent"] == base
    assert kb_profile.kb_commit(ms) == fix
    # and the resolver now maps the fixed commit to the same profile
    res = kb_profile.resolve("ecosim", commit=fix, model_path=m, repo=r)
    assert (res.profile, res.via) == ("toy-base", "patch")


def test_apply_refuses_a_commit_that_does_not_descend(kbrepo):
    r, m, base, fix = kbrepo
    assert kb_patch.run("toy-base", fix, m, apply=True, summary="x", report=None, repo=r) == 0
    # the knowledge base is now at `fix`; going back to `base` is not a patch
    assert kb_patch.run("toy-base", base, m, apply=True, summary="x", report=None, repo=r) == 1


def test_apply_refuses_a_legacy_profile(kbrepo):
    r, m, base, fix = kbrepo
    assert kb_patch.run("toy-old", fix, m, apply=True, summary="x", report=None, repo=r) == 1


def test_resolve_without_a_commit_asks_the_model_detector(kbrepo):
    """No --commit: the commit comes from `models/ecosim/version.py`'s detector (here the toy
    checkout's HEAD, the fix), not from this module."""
    r, m, base, fix = kbrepo
    with pytest.raises(kb_profile.NoMatch, match="AHEAD"):
        kb_profile.resolve("ecosim", model_path=m, repo=r)
    assert kb_patch.run("toy-base", fix, m, apply=True, summary="x", report=None, repo=r) == 0
    assert kb_profile.resolve("ecosim", model_path=m, repo=r).via == "patch"


def test_a_new_source_file_is_reported(kbrepo, tmp_path):
    r, m, base, fix = kbrepo
    rep = tmp_path / "plan.md"
    kb_patch.run("toy-base", fix, m, apply=False, summary=None, report=str(rep), repo=r)
    text = rep.read_text()
    section = text.split("## New source files")[1].split("##")[0]
    assert "`src/New.F90`" in section


def test_a_fates_profile_is_refused(kbrepo):
    """FATES's knowledge base spans ELM and FATES and is versioned by API epoch: not one diff."""
    r, m, base, fix = kbrepo
    assert kb_patch.run("toy-fates", fix, m, apply=False, summary=None, report=None, repo=r) == 1


def test_the_grammar_comes_from_the_model_spec():
    """ATS is C++: its spec, not this tool, says what a source file and a routine are."""
    g = kb_patch.Grammar.for_model("ats")
    assert g.full.search("see src/pks/flow/richards.cc:120 here")
    assert not g.full.search("see src/Mod.F90:12 here")
    lines = ["int x;", "void Richards::Solve(double t) {", "  double y = t;", "}"]
    assert g.enclosing(lines, 3) == "Solve"
    f = kb_patch.Grammar.for_model("ecosim")
    assert f.full.search("src/Mod.F90:12") and f.enclosing(MOD_BASE.splitlines(), 13) == "Gamma"
