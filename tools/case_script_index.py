#!/usr/bin/env python3
"""Generate, or check, the index in a case's `scripts/` and `case_template/` READMEs from each file's own first line.

visibility: public

WHY. A phase is told to start from the case's templates before writing a script or a run file, and
the README in each folder is what an agent reads to choose. A hand-kept table drifts: one case's
`scripts/README.md` listed 3 of its 29 templates, and the `case_template/README.md` files named 1 to
4 of their 3 to 7 run files. A reader who READ the README still could not see most of what was
there, and a phase script was written from scratch beside a template that already did the job. The
index is now DERIVED from the files themselves, so it cannot list one that is gone or omit one that
was added.

TWO TIERS, one block in each folder's README between two markers:

    scripts/         script TEMPLATES (`*.py`, `*.sh`) a phase copies into its phase_results/{stem}/
                     and adapts. Each must carry a summary line (its first docstring line, or a shell
                     script's first comment), because the index is how a phase chooses one.
    case_template/   the RUN FILES staged into a case or adapted for a launch: launchers, namelists,
                     decks, manifests -- every file but the README. A summary is shown where the file
                     has one (first comment, or a markdown file's first heading) and is not required:
                     a namelist's comments count against EcoSIM's fixed 4096-byte read buffer.

Everything outside the markers is hand-written and left alone. A README without the markers gets the
block as a new section before its second `## ` heading, so the index sits near the top.

WHAT COUNTS AS A FILE. What the BRANCH carries, plus new untracked files not ignored by git
(`git ls-files --cached --others --exclude-standard`), never a raw directory walk.

    python3 tools/case_script_index.py --case use_cases/<Case> [--tier scripts|case_template] [--write]
    python3 tools/case_script_index.py --staged                            # tiers with a staged change

Exit 0 current, 1 stale or a script template without a summary line (blocking in pre-commit 32).

Kept importable by Python 3.6: two hooks import it, and they run under the system `python3`.

Author: Jing Tao with Claude on Perlmutter
"""
import argparse
import ast
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- template-index:begin (generated by tools/case_script_index.py; do not edit by hand) -->"
END = "<!-- template-index:end -->"
NO_SUMMARY = "(no summary line: give this template a docstring)"
TIERS = ("scripts", "case_template")
# per tier: which files count, whether a summary line is required, and how the block is labelled
TIER_SPEC = {
    "scripts": dict(suffixes=(".py", ".sh"), need_summary=True, heading="Template index",
                    header="| template | what it is (its own first docstring line) |",
                    empty="| _(none yet)_ | the first script written for a second time is promoted here |"),
    "case_template": dict(suffixes=None, need_summary=False, heading="Run-file index",
                          header="| run file | what it is (its own first comment or heading line) |",
                          empty="| _(none yet)_ | the model's run files are staged here when the case is set up |"),
}
# A template's docstring often opens with the word TEMPLATE; in an index of templates it is noise.
_PREFIX = re.compile(r"^TEMPLATE\s*(?:[:.\-]|—)\s*")
_RULE = re.compile(r"^[\W_]*$")       # a decoration line: ====, ----, nothing alphanumeric


def summary_of(path):
    """The file's own one-liner: a Python docstring's first line, a shell or namelist file's first
    meaningful comment (skipping the shebang, #SBATCH directives and ruler lines), or a markdown
    file's first heading."""
    try:
        text = path.read_text(errors="replace")
    except OSError:
        return NO_SUMMARY
    first = ""
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text)) or ""
        except SyntaxError:
            doc = ""
        first = next((l.strip() for l in doc.splitlines() if l.strip()), "")
    elif path.suffix == ".md":
        first = next((l.lstrip("#").strip() for l in text.splitlines() if l.strip()), "")
    else:
        mark = "!" if path.suffix == ".nml" else "#"
        for line in text.splitlines():
            s = line.strip()
            if not s or s.startswith("#!") or s.upper().startswith("#SBATCH"):
                continue
            if not s.startswith(mark):
                break
            body = s.lstrip(mark).strip()
            if body and not _RULE.match(body):
                first = body.strip("-= ").strip()
                break
    first = _PREFIX.sub("", first).replace("|", "\\|")
    return first or NO_SUMMARY


def templates(case, root=ROOT, tier="scripts"):
    spec = TIER_SPEC[tier]
    rel = case.resolve().relative_to(root.resolve()) / tier
    out = subprocess.run(["git", "-C", str(root), "ls-files", "--cached", "--others",
                          "--exclude-standard", "--", str(rel)],
                         stdout=subprocess.PIPE, universal_newlines=True).stdout.split()
    seen = sorted({root / p for p in out
                   if Path(p).parent == rel and Path(p).name != "README.md"
                   and (spec["suffixes"] is None or p.endswith(spec["suffixes"]))})
    return [p for p in seen if p.is_file()]


def render(case, root=ROOT, tier="scripts"):
    spec = TIER_SPEC[tier]
    rows = []
    for p in templates(case, root, tier):
        s = summary_of(p)
        rows.append("| `%s` | %s |" % (p.name, s if (s != NO_SUMMARY or spec["need_summary"]) else "--"))
    return "\n".join([BEGIN, "", spec["header"], "|---|---|", *(rows or [spec["empty"]]), "", END])


def current_block(readme):
    if not readme.is_file():
        return None
    text = readme.read_text()
    if BEGIN not in text or END not in text:
        return None
    return text[text.index(BEGIN): text.index(END) + len(END)]


def check(case, root=ROOT, tiers=TIERS):
    """Problems with this case's indexes, for the tiers asked about; empty when current."""
    problems = []
    for tier in tiers:
        if not (case / tier).is_dir():
            continue
        readme = case / tier / "README.md"
        files = templates(case, root, tier)
        want, have = render(case, root, tier), current_block(readme)
        if have is None:
            if files:
                problems.append("%s: %s/README.md has no generated index" % (case.name, tier))
        elif have != want:
            listed = set(re.findall(r"^\| `([^`]+)` \|", have, re.M))
            actual = {p.name for p in files}
            for n in sorted(actual - listed):
                problems.append("%s: `%s/%s` is not in the index" % (case.name, tier, n))
            for n in sorted(listed - actual):
                problems.append("%s: the %s index lists `%s`, which is not there" % (case.name, tier, n))
            if not (actual ^ listed):
                problems.append("%s: a summary line in %s/ changed since the index was written"
                                % (case.name, tier))
        if TIER_SPEC[tier]["need_summary"]:
            for p in files:
                if summary_of(p) == NO_SUMMARY:
                    problems.append("%s: template `%s` has no summary line to index" % (case.name, p.name))
    return problems


def _insert(text, section):
    """Put a new section before the README's second `## ` heading, or at the end."""
    heads = [m.start() for m in re.finditer(r"^## ", text, re.M)]
    if len(heads) >= 2:
        return text[: heads[1]] + section + "\n" + text[heads[1]:]
    return text.rstrip("\n") + "\n\n" + section


def write(case, root=ROOT, tiers=TIERS):
    written = []
    for tier in tiers:
        if not (case / tier).is_dir():
            continue
        readme = case / tier / "README.md"
        block = render(case, root, tier)
        section = "## %s\n\n%s\n" % (TIER_SPEC[tier]["heading"], block)
        if readme.is_file():
            text = readme.read_text()
            if BEGIN in text and END in text:
                text = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END):]
            else:
                text = _insert(text, section)
        else:
            text = "# `%s/`\n\n%s" % (tier, section)
        readme.write_text(text)
        written.append((readme, len(templates(case, root, tier))))
    return written


def staged_targets():
    """{case dir: set of tiers} with a staged change."""
    names = subprocess.run(["git", "-C", str(ROOT), "diff", "--cached", "--name-only",
                            "--diff-filter=ACMRD"], stdout=subprocess.PIPE, universal_newlines=True).stdout.split()
    out = {}
    for n in names:
        m = re.match(r"^use_cases/([^/]+)/(scripts|case_template)/", n)
        if m and (ROOT / "use_cases" / m.group(1)).is_dir():
            out.setdefault(ROOT / "use_cases" / m.group(1), set()).add(m.group(2))
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--case", action="append", type=Path, default=[],
                    help="use_cases/<Case> (repeatable); both tiers")
    ap.add_argument("--staged", action="store_true", help="only the tiers with a staged change")
    ap.add_argument("--tier", action="append", choices=TIERS, default=[],
                    help="limit --case to this folder (repeatable); default both")
    ap.add_argument("--write", action="store_true", help="regenerate the blocks in place")
    a = ap.parse_args(argv)
    targets = {(c if c.is_absolute() else ROOT / c): set(a.tier or TIERS) for c in a.case}
    if a.staged:
        for c, t in staged_targets().items():
            targets.setdefault(c, set()).update(t)
    if not targets:
        ap.error("name a --case, or pass --staged")
    if a.write:
        for c, tiers in targets.items():
            for readme, n in write(c, ROOT, [t for t in TIERS if t in tiers]):
                print("wrote %s (%d files)" % (readme.relative_to(ROOT), n))
        return 0
    problems = [p for c, tiers in targets.items() for p in check(c, ROOT, [t for t in TIERS if t in tiers])]
    if not problems:
        print("case_script_index: index current for %d case(s)" % len(targets))
        return 0
    for p in problems:
        print("case_script_index: %s" % p)
    print("  Regenerate: python3 tools/case_script_index.py --case use_cases/<Case> --write")
    return 1


if __name__ == "__main__":
    sys.exit(main())
