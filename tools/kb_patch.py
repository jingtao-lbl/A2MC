class Grammar:
    """What counts as a source file and as a routine declaration, read from the MODEL'S OWN spec
    (`models/<model>/spec.py`: `source_extensions`, `routine_decl_patterns`), the same fields
    `tools/validate_wiki_vs_source.py` dispatches on. Fortran for EcoSIM and PFLOTRAN, C++ for ATS;
    this tool does not decide."""

    def __init__(self, source_extensions, routine_decl_patterns):
        exts = "|".join(re.escape(e.lstrip(".")) for e in source_extensions)
        self.full = re.compile(rf"(?P<path>(?:[\w.-]+/)*(?P<file>[A-Za-z_][\w.-]*\.(?:{exts})))"
                               rf":(?P<a>\d+)(?:-(?P<b>\d+))?(?![\d])")
        self.file_only = re.compile(rf"(?:[\w.-]+/)*(?P<file>[A-Za-z_][\w.-]*\.(?:{exts}))(?![\w])")
        self.routines = [re.compile(p, re.I) for p in routine_decl_patterns]

    @classmethod
    def for_model(cls, model: str) -> "Grammar":
        sys.path.insert(0, str(REPO / "tools"))
        from validate_wiki_vs_source import load_spec  # noqa: E402  the shared ModelSpec loader
        spec = load_spec(model)
        if not spec.source_extensions or not spec.routine_decl_patterns:
            raise SystemExit(f"models/{model}/spec.py declares no source_extensions / routine_decl_patterns")
        return cls(spec.source_extensions, spec.routine_decl_patterns)

    def enclosing(self, lines, lineno: int) -> str | None:
        """The nearest routine declared at or above `lineno`; a line closing a routine (`end ...`)
        is not a declaration."""
        for k in range(min(lineno, len(lines)) - 1, -1, -1):
            if re.match(r"\s*end\b", lines[k], re.I):
                if k != lineno - 1:
                    return None
                continue
            for rx in self.routines:
                m = rx.search(lines[k])
                if m:
                    return m.group(m.lastindex or 0)    # `Foo::bar(` names the method, the last group
        return None


BARE = re.compile(r"(?<![\w/.\-]):(?P<a>\d+)(?:-(?P<b>\d+))?(?![\d])")
HEADING = re.compile(r"^#{1,6}\s")
PIN = re.compile(r"^\*\*Source pin:\*\*")
INDEX_BEGIN, INDEX_END = "<!-- kb-patches:begin -->", "<!-- kb-patches:end -->"


def _git(path, *args) -> str:
    r = subprocess.run(["git", "-C", str(path), *args], capture_output=True, text=True)
    if r.returncode:
        raise SystemExit(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout


# ------------------------------------------------------------------------------------------------
# The line map: old commit -> new commit, per file
# ------------------------------------------------------------------------------------------------

def line_maps(model_path, old: str, new: str) -> dict:
    """{old_path: {"new_path", "deleted", "hunks": [(os, oc, ns, nc), ...]}} from `git diff -U0 -M`."""
    out: dict = {}
    cur = None
    for ln in _git(model_path, "diff", "-U0", "-M", "--no-color", "--no-ext-diff", old, new).splitlines():
        if ln.startswith("diff --git "):
            m = re.match(r"diff --git a/(.+) b/(.+)$", ln)
            cur = {"new_path": m.group(2), "deleted": False, "hunks": []}
            out[m.group(1)] = cur
        elif cur is None:
            continue
        elif ln.startswith("rename to "):
            cur["new_path"] = ln[len("rename to "):]
        elif ln.startswith("+++ /dev/null"):
            cur["deleted"] = True
        else:
            m = re.match(r"@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@", ln)
            if m:
                cur["hunks"].append((int(m[1]), int(m[2] if m[2] is not None else 1),
                                     int(m[3]), int(m[4] if m[4] is not None else 1)))
    return out


def map_range(entry: dict, a: int, b: int):
    """('untouched'|'shift'|'content'|'deleted', new_a, new_b) for old lines a..b of one file."""
    if entry["deleted"]:
        return "deleted", a, b
    for os_, oc, _ns, _nc in entry["hunks"]:
        if oc > 0 and os_ <= b and os_ + oc - 1 >= a:
            return "content", a, b                  # a cited line was changed or removed
        if oc == 0 and a <= os_ < b:
            return "content", a, b                  # lines were inserted INSIDE the cited range

    def off(line: int) -> int:
        return sum(nc - oc for os_, oc, _ns, nc in entry["hunks"]
                   if (oc > 0 and os_ + oc - 1 < line) or (oc == 0 and os_ < line))

    na, nb = a + off(a), b + off(b)
    return ("shift" if (na, nb) != (a, b) else "untouched"), na, nb


class FileIndex:
    """Resolve a cited path or bare basename to the repository path it means, at the old commit."""

    def __init__(self, model_path, old: str):
        self.paths = _git(model_path, "ls-tree", "-r", "--name-only", old).splitlines()
        self.by_base: dict = defaultdict(list)
        for p in self.paths:
            self.by_base[os.path.basename(p)].append(p)
        self.pathset = set(self.paths)

    def resolve(self, cited: str) -> str | None:
        if cited in self.pathset:
            return cited
        hits = [p for p in self.by_base.get(os.path.basename(cited), []) if p.endswith(cited)]
        return hits[0] if len(hits) == 1 else None


# ------------------------------------------------------------------------------------------------
# Rewriting one text file
# ------------------------------------------------------------------------------------------------

def _fmt(a: int, b: int, had_range: bool) -> str:
    return f"{a}-{b}" if had_range else f"{a}"


IDENT = re.compile(r"`([A-Za-z_]\w{3,})")
def corroborated(lines, a: int, b: int, ids: set, grammar: Grammar) -> bool:
    """Does the cited code mention what the wiki line talks about? An identifier from the line within
    three lines of the cited range, or the line naming the routine that encloses it."""
    if not lines or a > len(lines):
        return False
    window = "\n".join(lines[max(0, a - 4):min(len(lines), b + 3)])
    if any(re.search(rf"\b{re.escape(x)}\b", window) for x in ids):
        return True
    r = grammar.enclosing(lines, a)
    return bool(r) and r.lower() in {x.lower() for x in ids}


def patch_text(text: str, maps: dict, index: FileIndex, where: str, records: list,
               old_lines, grammar: Grammar) -> str:
    """Return `text` with every shifted citation re-anchored; append one record per citation that
    lands in a changed file (shift, content, deleted) or whose file cannot be established.

    A FULL citation names its file. A BARE `:NNN` citation is attributed first by position (the
    nearest file named before it on its line, else above it outside a table within its section or a
    parent section), then VERIFIED by content against the old commit: kept only when an identifier
    from the wiki line is near the cited line, or the line names the enclosing routine. If the
    positional file fails, every file the page names is tried and a unique corroborated one is used.
    A bare citation that cannot be established is left as written and recorded as `bare-uncertain`
    whenever one of the page's files changed. Measured on the cb243228 wiki: position alone moved
    `:71` beside `Run_EcoSIM_one_step` by the offset of `EcoSIMCtrlMod.F90` instead of
    `EcoSIMAPI.F90`, because the section's prose named the former."""
    FULL, FILE_ONLY = grammar.full, grammar.file_only
    lines = text.splitlines(keepends=True)
    page_files = []
    for fm in FILE_ONLY.finditer(text):
        rp = index.resolve(fm.group(0))
        if rp and rp not in page_files:
            page_files.append(rp)
    page_touches_change = any(f in maps for f in page_files)
    # The file a bare citation belongs to is scoped like the sections themselves: a heading clears
    # what its own level and deeper levels named, so a `### 2.3` subsection still inherits the file
    # its `## 2` section named; a file named in one TABLE ROW governs only the rest of that row.
    by_level: dict = {}
    level = 0
    for i, line in enumerate(lines):
        if HEADING.match(line):
            level = len(line) - len(line.lstrip("#"))
            for k in [k for k in by_level if k >= level]:
                del by_level[k]
        context_file = by_level[max(by_level)] if by_level else None
        spans = [("full", m) for m in FULL.finditer(line)]
        masked = FULL.sub(lambda m: " " * len(m.group(0)), line)
        spans += [("bare", m) for m in BARE.finditer(masked)]
        spans.sort(key=lambda s: s[1].start())
        file_mentions = [(fm.start(), fm.group(0)) for fm in FILE_ONLY.finditer(line)]
        ids = set(IDENT.findall(line))
        pieces, pos, changed = [], 0, False
        for kind, m in spans:
            a = int(m.group("a"))
            b = int(m.group("b") or a)
            if kind == "full":
                repo_path = index.resolve(m.group("path"))
                how = "named"
            else:
                before = [f for s, f in file_mentions if s < m.start()]
                cand = index.resolve(before[-1] if before else context_file or "") if (before or context_file) else None
                if not page_touches_change:
                    continue                          # nothing this page could cite has changed
                def outcome(f):                       # what attributing the citation to f would do
                    return map_range(maps[f], a, b) if f in maps else ("untouched", a, b)
                repo_path, how = None, None
                hits = [f for f in page_files if corroborated(old_lines(f), a, b, ids, grammar)]
                agree = len({outcome(f) for f in hits}) <= 1
                if cand and cand in hits and agree:
                    repo_path, how = cand, "verified"     # position, confirmed by content
                elif hits and agree:
                    repo_path, how = hits[0], "content"   # position was wrong; content fits one way
                elif cand and not hits:
                    repo_path, how = cand, "position"     # nothing confirms or contradicts it
                if repo_path is None:
                    # Unaffected whichever file it means, unless attributing it to some file the page
                    # names would move or flag it. Also ambiguous: two files fit and disagree
                    # (a member declared in one module and defaulted in another, a few lines apart).
                    if any(outcome(f)[0] != "untouched" for f in (hits or page_files)):
                        records.append({"where": where, "line": i + 1, "kind": "bare-uncertain",
                                        "text": m.group(0), "file": cand,
                                        "candidates": hits})
                    continue
            ent = maps.get(repo_path) if repo_path else None
            if ent is None:
                continue
            status, na, nb = map_range(ent, a, b)
            records.append({"where": where, "line": i + 1, "kind": status, "bare": kind == "bare",
                            "attributed": how, "file": repo_path,
                            "old": f"{a}" + (f"-{b}" if m.group("b") else ""),
                            "new": _fmt(na, nb, bool(m.group("b")))})
            renamed = ent["new_path"] != repo_path
            if status != "shift" and not (renamed and status == "untouched" and kind == "full"):
                continue
            if kind == "full":
                path = m.group("path")
                if renamed:
                    path = (ent["new_path"] if path == repo_path
                            else path[: -len(os.path.basename(repo_path))] + os.path.basename(ent["new_path"]))
                new = f"{path}:{_fmt(na, nb, bool(m.group('b')))}"
            else:
                new = f":{_fmt(na, nb, bool(m.group('b')))}"
            pieces.append(line[pos:m.start()])
            pieces.append(new)
            pos = m.end()
            changed = True
        if file_mentions and not line.lstrip().startswith("|"):
            by_level[level] = file_mentions[-1][1]
        if changed:
            pieces.append(line[pos:])
            lines[i] = "".join(pieces)
    return "".join(lines)


class OldSource:
    """Cached `git show <old>:<path>` lines, for verifying bare citations against the text the wiki
    was written from."""

    def __init__(self, model_path, old: str):
        self.model_path, self.old, self.cache = model_path, old, {}

    def __call__(self, path: str) -> list:
        if path not in self.cache:
            r = subprocess.run(["git", "-C", str(self.model_path), "show", f"{self.old}:{path}"],
                               capture_output=True, text=True)
            self.cache[path] = r.stdout.splitlines() if r.returncode == 0 else []
        return self.cache[path]


def kb_files(ms: dict, repo: Path = REPO) -> tuple[list[Path], list[Path], Path | None]:
    """(hand-written wiki pages, generated wiki pages, curated seed) of a profile."""
    wiki = repo / ms["knowledge_base_dir"] / ms["model_wiki_subdir"] if ms.get("model_wiki_subdir") else None
    pages, generated = [], []
    if wiki and wiki.is_dir():
        for p in sorted(wiki.rglob("*.md")):
            if any(part.startswith(".") for part in p.relative_to(wiki).parts):
                continue
            (generated if "**Generated by:**" in p.read_text()[:800] else pages).append(p)
    seed = repo / ms["curated_yaml_path"] if ms.get("curated_yaml_path") else None
    return pages, generated, seed


def set_pin(text: str, base8: str, to8: str) -> str:
    out = []
    for line in text.splitlines(keepends=True):
        if PIN.match(line):
            body = line.rstrip("\n")
            body = re.sub(r" ?· patched to `[0-9a-f]+` \(see the wiki `index\.md`, Patches applied\)", "", body)
            line = f"{body} · patched to `{to8}` (see the wiki `index.md`, Patches applied)\n"
        out.append(line)
    return "".join(out)


def index_table(ms: dict) -> str:
    rows = ["| # | commit | on top of | summary | source files | citations re-anchored | flagged for review |",
            "|---|---|---|---|---|---|---|"]
    for i, p in enumerate(ms.get("patches") or [], 1):
        rows.append(f"| {i} | `{p['commit'][:8]}` | `{p['parent'][:8]}` | {p['summary']} | "
                    f"{', '.join(f'`{f}`' for f in p.get('source_files', []))} | "
                    f"{p.get('citations_reanchored', 0)} | {p.get('citations_flagged', 0)} |")
    return "\n".join(rows)


def set_index(text: str, ms: dict) -> str:
    block = (f"{INDEX_BEGIN}\n## Patches applied\n\nThis knowledge base describes base commit "
             f"`{base_commit(ms)[:8]}` with the fixes below patched in place by `tools/kb_patch.py`; "
             f"citations in every page are at `{kb_commit(ms)[:8]}`. Citations a patch flagged were "
             f"reviewed by hand before it was committed.\n\n{index_table(ms)}\n{INDEX_END}\n")
    if INDEX_BEGIN in text:
        return re.sub(re.escape(INDEX_BEGIN) + r".*?" + re.escape(INDEX_END) + r"\n?", block, text, flags=re.S)
    return text.rstrip("\n") + "\n\n" + block


