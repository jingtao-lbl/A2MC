def run(profile: str, to: str, model_path, apply: bool, summary: str | None, report: str | None,
        repo: Path = REPO) -> int:
    reg = registry(repo)
    if profile not in reg:
        raise SystemExit(f"unknown profile {profile!r}")
    ms = reg[profile]
    if model_of(ms) == "fates":
        print(f"REFUSED: {profile} is a FATES profile. Its knowledge base spans the ELM and FATES "
              f"checkouts and is versioned by API epoch, so a patch is not one diff; use the FATES "
              f"rebuild tiers (docs/a2mc_reference/version_association_workflow.md).")
        return 1
    if ms.get("legacy"):
        print(f"REFUSED: {profile} is legacy; patch the live profile or register a new milestone")
        return 1
    old = full_sha(model_path, kb_commit(ms) or "")
    new = full_sha(model_path, to)
    if not old or not new:
        raise SystemExit(f"cannot resolve {kb_commit(ms)} or {to} in {model_path}")
    if old == new:
        print(f"nothing to do: {profile}'s knowledge base is already at {new[:8]}")
        return 1
    if subprocess.run(["git", "-C", str(model_path), "merge-base", "--is-ancestor", old, new]).returncode:
        print(f"REFUSED: {new[:8]} does not descend from {profile}'s knowledge base {old[:8]}. A patch "
              f"is a fix ON TOP of the round's base binary; anything else is a new milestone.")
        return 1
    maps = line_maps(model_path, old, new)
    index = FileIndex(model_path, old)
    old_src = OldSource(model_path, old)
    grammar = Grammar.for_model(model_of(ms))
    pages, generated, seed = kb_files(ms, repo)
    targets = pages + ([seed] if seed and seed.exists() else [])
    records: list = []
    rewritten = {}
    for p in targets:
        t = p.read_text()
        nt = patch_text(t, maps, index, str(p.relative_to(repo)), records, old_src, grammar)
        if nt != t:
            rewritten[p] = nt
    tally = Counter(r["kind"] for r in records)
    added = [f for f in _git(model_path, "diff", "--name-only", "--diff-filter=A", old, new).splitlines()
             if grammar.file_only.fullmatch(f)]
    flagged = [r for r in records if r["kind"] in ("content", "deleted")]
    changed_files = sorted(maps)
    lines = [f"# Knowledge-base patch plan: {profile}, {old[:8]} -> {new[:8]}", "",
             f"Source files changed: {len(changed_files)} ({', '.join(f'`{f}`' for f in changed_files)})", "",
             f"Citations in changed files: shift {tally['shift']}, content {tally['content']}, "
             f"deleted {tally['deleted']}, untouched {tally['untouched']}; bare citations whose file could not "
             f"be established (left as written, listed below): {tally['bare-uncertain']}.",
             f"Files rewritten: {len(rewritten)}. Generated pages to regenerate at `{new[:8]}`: "
             + (", ".join(f"`{p.relative_to(repo)}`" for p in generated) or "none") + ".", "",
             "## New source files (the knowledge base cannot cite them yet: document them by hand)", "",
             ("\n".join(f"- `{f}`" for f in added) or "None."), "",
             "## Flagged for review (the cited code changed)", ""]
    by_where = defaultdict(list)
    for r in flagged:
        by_where[r["where"]].append(r)
    for w, rs in by_where.items():
        lines.append(f"- `{w}`: " + "; ".join(f"line {r['line']} cites `{r['file']}:{r['old']}`"
                                               + (" (bare)" if r.get("bare") else "") for r in rs))
    if not flagged:
        lines.append("None.")
    unverified = [r for r in records if r.get("attributed") == "position" and r["kind"] != "untouched"]
    lines += ["", f"## Bare citations moved on position alone ({len(unverified)}; nothing on the line confirms the "
              "file, nothing contradicts it: spot-check)", ""]
    by_where_p = defaultdict(list)
    for r in unverified:
        by_where_p[r["where"]].append(r)
    for w, rs in by_where_p.items():
        lines.append(f"- `{w}`: " + "; ".join(f"line {r['line']} `:{r['old']}` -> `:{r['new']}` in `{r['file']}`"
                                               for r in rs))
    if not unverified:
        lines.append("None.")
    uncertain = [r for r in records if r["kind"] == "bare-uncertain"]
    lines += ["", "## Bare citations whose file could not be established (left as written; check by hand)", ""]
    by_where_u = defaultdict(list)
    for r in uncertain:
        by_where_u[r["where"]].append(r)
    for w, rs in by_where_u.items():
        lines.append(f"- `{w}`: " + "; ".join(f"line {r['line']} `{r['text'].strip()}`"
                                               + (f" (position suggests `{r['file']}`)" if r.get("file") else "")
                                               for r in rs))
    if not uncertain:
        lines.append("None.")
    rep = "\n".join(lines) + "\n"
    print(rep)
    if report:
        Path(report).write_text(rep)
    if not apply:
        return 0
    if not summary:
        raise SystemExit("apply needs --summary")
    for p, nt in rewritten.items():
        p.write_text(nt)
    patch = {"commit": new, "parent": old, "date": datetime.date.today().isoformat(), "summary": summary,
             "source_files": changed_files, "new_source_files": added,
             "citations_reanchored": tally["shift"], "citations_flagged": len(flagged)}
    mj_path = repo / "rag/milestones.json"
    mj = json.loads(mj_path.read_text())
    mj["milestones"][profile].setdefault("patches", []).append(patch)
    mj_path.write_text(json.dumps(mj, indent=2) + "\n")
    ms = mj["milestones"][profile]
    for p in pages:
        t = p.read_text()
        nt = set_pin(t, base_commit(ms)[:8], new[:8])
        if p.name == "index.md" and p.parent.name == ms["model_wiki_subdir"]:
            nt = set_index(nt, ms)
        if nt != t:
            p.write_text(nt)
    print(f"APPLIED: {tally['shift']} citation(s) re-anchored in {len(rewritten)} file(s); patch "
          f"{new[:8]} registered on {profile}. Next: review the {len(flagged)} flagged citation(s), "
          f"regenerate the generated pages at {new[:8]}, rebuild {profile}, run its validators.")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mode", choices=("plan", "apply"))
    ap.add_argument("--profile", required=True)
    ap.add_argument("--to", required=True, help="the commit the knowledge base should describe")
    ap.add_argument("--model-path", default=os.environ.get("A2MC_MODEL_PATH"))
    ap.add_argument("--summary", help="apply: one line saying what the fix does")
    ap.add_argument("--report", help="also write the plan to this Markdown file")
    a = ap.parse_args()
    if not a.model_path:
        print("ERROR: no --model-path and $A2MC_MODEL_PATH is unset", file=sys.stderr)
        return 2
    return run(a.profile, a.to, a.model_path, a.mode == "apply", a.summary, a.report)


