#!/usr/bin/env python
"""Patch a registered knowledge base IN PLACE for a small change to the model source.

visibility: public
Author: Jing Tao with Claude on Perlmutter

A profile in `rag/milestones.json` is the knowledge base for a calibration round's BASE binary. When
a small fix lands on top of that base (a bug fix the round adopts, a default-off switch), the
knowledge base is patched, not rebuilt from scratch: the profile keeps its name and its base commit,
and gains a `patches` entry recording the new commit. `tools/kb_profile.py` then resolves both the
base and every patched commit to the same profile. A NEW milestone is for a new base binary.

WHAT A PATCH TOUCHES. Every `path/File.F90:NNN[-MMM]` citation in the profile's wiki pages and its
curated seed is classified against `git diff -U0 -M <kb commit> <new commit>`:

  untouched   the cited file did not change, or changed only after the cited lines: kept as is
  shift       the cited lines are unchanged but moved: RE-ANCHORED to their new line numbers
  content     the cited lines (or an insertion inside the cited range) changed: LEFT AS WRITTEN and
              listed for review, because what the text says about that code may no longer be true
  deleted     the cited file no longer exists: listed for review

A source file the change ADDS cannot be cited by the knowledge base yet; the report lists it so
its documentation is written by hand. What counts as a source file and as a routine declaration
comes from the model's own spec (`source_extensions`, `routine_decl_patterns`). FATES profiles are
refused: their knowledge base spans two checkouts and is versioned by API epoch.

A bare `:NNN` citation is attributed by position (the nearest file named before it on its line, else
above it outside a table within its section or a parent section) and checked against the old commit's
text: a file CORROBORATES it when an identifier from the wiki line sits near the cited line, or the
line names the routine enclosing it. The positional file is used when it corroborates, or when no file
the page names does; a different file is used when it alone corroborates (or all that do agree on the
outcome). When corroborating files disagree, the citation is left as written and listed for review.
Moves made on position alone are listed separately so they can be spot-checked. Pages headed `**Generated by:**` are not edited: their generator is re-run at
the new commit instead. Hidden directories (an editor's autosave) are never read.

`apply` also updates every page's `**Source pin:**` line to state the patch level, maintains a
`Patches applied` table in the wiki's `index.md`, and appends the patch to the milestone.

Run (from the repository root, with the model checkout in $A2MC_MODEL_PATH):
  python tools/kb_patch.py plan  --profile <name> --to <commit> [--report out.md]
  python tools/kb_patch.py apply --profile <name> --to <commit> --summary "one line" [--report out.md]
Then: review what `content` lists, regenerate the generated pages at the new commit, rebuild the
SAME profile (its builder reads the patched commit), and run the profile's validators.
Exit 0 ok; 1 refused (not a descendant, nothing to do, or the profile is legacy); 2 bad usage.
"""
